import React, { useState } from 'react';
import { CareerRecommendation, StudentProfile } from '../types/career';
import { POPULAR_CAREER_TRACKS } from '../data/careerData';
import {
  Sparkles,
  TrendingUp,
  DollarSign,
  Building2,
  CheckCircle,
  AlertCircle,
  ArrowRight,
  Filter,
  RefreshCw,
  Award,
  Layers,
  Compass
} from 'lucide-react';

interface CareerRecommenderTabProps {
  studentProfile: StudentProfile;
  onSelectRoleForGap: (roleName: string) => void;
  onNavigateTab: (tabId: string) => void;
}

export const CareerRecommenderTab: React.FC<CareerRecommenderTabProps> = ({
  studentProfile,
  onSelectRoleForGap,
  onNavigateTab
}) => {
  const [selectedDomain, setSelectedDomain] = useState<string>('All');
  const [recommendations, setRecommendations] = useState<CareerRecommendation[]>(POPULAR_CAREER_TRACKS);
  const [isLoadingAi, setIsLoadingAi] = useState(false);
  const [aiGeneratedNotice, setAiGeneratedNotice] = useState(false);

  const domains = ['All', 'Software & Web Development', 'Artificial Intelligence & Data', 'Infrastructure & Cloud Systems', 'Security & Information Assurance', 'Product Strategy & Tech Leadership', 'Design & Human-Computer Interaction'];

  const filteredTracks = selectedDomain === 'All'
    ? recommendations
    : recommendations.filter(r => r.domain === selectedDomain);

  const handleGenerateAiRecommendations = async () => {
    setIsLoadingAi(true);
    try {
      const res = await fetch('/api/career/recommend', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ studentProfile })
      });
      const data = await res.json();
      if (data.success && Array.isArray(data.recommendations) && data.recommendations.length > 0) {
        setRecommendations([...data.recommendations, ...POPULAR_CAREER_TRACKS]);
        setAiGeneratedNotice(true);
      }
    } catch (err) {
      console.error('Failed to generate AI recommendations:', err);
    } finally {
      setIsLoadingAi(false);
    }
  };

  return (
    <div className="space-y-6">
      {/* Hero Banner / Profile Summary */}
      <div className="bg-gradient-to-r from-indigo-900 via-indigo-800 to-slate-900 rounded-2xl p-6 text-white shadow-xl relative overflow-hidden">
        <div className="absolute right-0 top-0 bottom-0 w-1/3 bg-indigo-500/10 rounded-full blur-3xl pointer-events-none" />
        <div className="relative z-10 flex flex-col md:flex-row md:items-center justify-between gap-4">
          <div>
            <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-indigo-500/20 text-indigo-300 text-xs font-semibold uppercase tracking-wider mb-2 border border-indigo-400/20">
              <Compass className="w-3.5 h-3.5" />
              Tailored For {studentProfile.name}
            </div>
            <h2 className="text-2xl font-bold tracking-tight">Personalized Career Trajectories</h2>
            <p className="text-slate-300 text-sm mt-1 max-w-2xl leading-relaxed">
              Curated based on your <span className="text-white font-semibold">{studentProfile.degree} in {studentProfile.major}</span>, your skills ({studentProfile.technicalSkills.slice(0, 4).join(', ')}...), and primary goal: <span className="italic text-indigo-200 font-medium">"{studentProfile.goals}"</span>.
            </p>
          </div>

          <div className="flex flex-col sm:flex-row items-stretch sm:items-center gap-2 shrink-0">
            <button
              onClick={handleGenerateAiRecommendations}
              disabled={isLoadingAi}
              className="px-4 py-2.5 bg-indigo-500 hover:bg-indigo-400 text-white rounded-xl text-xs font-semibold flex items-center justify-center gap-2 transition-all shadow-md active:scale-95 disabled:opacity-75"
            >
              <RefreshCw className={`w-4 h-4 ${isLoadingAi ? 'animate-spin' : ''}`} />
              {isLoadingAi ? 'Consulting Gemini AI...' : 'Re-analyze with AI'}
            </button>
          </div>
        </div>

        {aiGeneratedNotice && (
          <div className="mt-4 p-2.5 rounded-lg bg-emerald-500/20 border border-emerald-500/30 text-emerald-200 text-xs flex items-center gap-2">
            <CheckCircle className="w-4 h-4 text-emerald-400" />
            New personalized recommendations generated by Gemini AI!
          </div>
        )}
      </div>

      {/* Domain Category Filter */}
      <div className="flex items-center gap-2 overflow-x-auto pb-1 scrollbar-none">
        <Filter className="w-4 h-4 text-slate-400 shrink-0 ml-1" />
        {domains.map(d => (
          <button
            key={d}
            onClick={() => setSelectedDomain(d)}
            className={`px-3.5 py-1.5 rounded-xl text-xs font-medium whitespace-nowrap transition-all ${
              selectedDomain === d
                ? 'bg-indigo-600 text-white shadow-sm font-semibold'
                : 'bg-white text-slate-600 hover:bg-slate-100 border border-slate-200'
            }`}
          >
            {d}
          </button>
        ))}
      </div>

      {/* Career Cards Grid */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
        {filteredTracks.map(career => {
          const matchColor = career.matchScore >= 90
            ? 'text-emerald-600 bg-emerald-50 border-emerald-200'
            : career.matchScore >= 80
            ? 'text-indigo-600 bg-indigo-50 border-indigo-200'
            : 'text-amber-600 bg-amber-50 border-amber-200';

          return (
            <div
              key={career.id}
              className="bg-white rounded-2xl border border-slate-200/90 hover:border-indigo-300 shadow-sm hover:shadow-md transition-all p-6 flex flex-col justify-between group"
            >
              <div>
                {/* Header info */}
                <div className="flex items-start justify-between gap-3 mb-3">
                  <div>
                    <span className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider block mb-1">
                      {career.domain}
                    </span>
                    <h3 className="text-xl font-bold text-slate-800 group-hover:text-indigo-600 transition-colors">
                      {career.title}
                    </h3>
                  </div>

                  <div className={`px-3 py-1.5 rounded-full border text-xs font-bold flex items-center gap-1.5 shrink-0 ${matchColor}`}>
                    <Sparkles className="w-3.5 h-3.5" />
                    <span>{career.matchScore}% Match</span>
                  </div>
                </div>

                {/* Summary */}
                <p className="text-xs text-slate-600 leading-relaxed mb-4">
                  {career.summary}
                </p>

                {/* Match Rationale Callout */}
                <div className="p-3 rounded-xl bg-slate-50 border border-slate-100 text-xs text-slate-700 mb-4">
                  <span className="font-semibold text-indigo-700 block mb-0.5">Why this fits your profile:</span>
                  <p className="text-slate-600 leading-normal">{career.rationale}</p>
                </div>

                {/* Key Metrics row */}
                <div className="grid grid-cols-3 gap-2 py-3 border-y border-slate-100 text-xs mb-4">
                  <div>
                    <span className="text-[10px] text-slate-400 uppercase block font-medium">Avg Salary</span>
                    <span className="font-bold text-slate-800 flex items-center gap-0.5 mt-0.5 text-[11px]">
                      <DollarSign className="w-3 h-3 text-emerald-600" />
                      {career.avgSalary}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] text-slate-400 uppercase block font-medium">Growth Rate</span>
                    <span className="font-bold text-slate-800 flex items-center gap-0.5 mt-0.5 text-[11px]">
                      <TrendingUp className="w-3 h-3 text-indigo-600" />
                      {career.growthRate}
                    </span>
                  </div>
                  <div>
                    <span className="text-[10px] text-slate-400 uppercase block font-medium">Hiring Demand</span>
                    <span className="font-bold text-emerald-700 mt-0.5 block text-[11px]">
                      {career.industryDemand}
                    </span>
                  </div>
                </div>

                {/* Required Skills Chips */}
                <div className="mb-4">
                  <span className="text-xs font-semibold text-slate-700 block mb-2">Core Industry Skills:</span>
                  <div className="flex flex-wrap gap-1.5">
                    {career.requiredSkills.map(req => {
                      const isOwned = studentProfile.technicalSkills.some(
                        s => s.toLowerCase().includes(req.skill.toLowerCase()) || req.skill.toLowerCase().includes(s.toLowerCase())
                      );

                      return (
                        <span
                          key={req.skill}
                          className={`text-[11px] px-2.5 py-1 rounded-lg border font-medium flex items-center gap-1 ${
                            isOwned
                              ? 'bg-emerald-50 text-emerald-700 border-emerald-200'
                              : req.importance === 'Essential'
                              ? 'bg-rose-50 text-rose-700 border-rose-200'
                              : 'bg-slate-100 text-slate-600 border-slate-200'
                          }`}
                        >
                          {isOwned && <CheckCircle className="w-3 h-3 text-emerald-600" />}
                          {req.skill}
                          <span className="text-[9px] opacity-75">({req.importance})</span>
                        </span>
                      );
                    })}
                  </div>
                </div>

                {/* Top Employers */}
                <div className="flex items-center gap-2 text-xs text-slate-500 mb-4">
                  <Building2 className="w-3.5 h-3.5 text-slate-400 shrink-0" />
                  <span className="font-medium text-slate-700">Top Employers:</span>
                  <span className="truncate">{career.topEmployers.join(', ')}</span>
                </div>
              </div>

              {/* Action Buttons */}
              <div className="pt-3 border-t border-slate-100 flex flex-wrap gap-2">
                <button
                  onClick={() => onSelectRoleForGap(career.title)}
                  className="flex-1 px-3 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-xs font-semibold flex items-center justify-center gap-1.5 transition-colors shadow-sm"
                >
                  <Layers className="w-3.5 h-3.5" />
                  Analyze Skill Gap
                </button>
                <button
                  onClick={() => onNavigateTab('roadmap')}
                  className="px-3 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-medium flex items-center justify-center gap-1 transition-colors"
                >
                  Roadmap
                  <ArrowRight className="w-3 h-3" />
                </button>
                <button
                  onClick={() => onNavigateTab('interview')}
                  className="px-3 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-medium flex items-center justify-center gap-1 transition-colors"
                >
                  Mock Interview
                </button>
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
